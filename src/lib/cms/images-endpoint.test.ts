test('upload endpoint: oversized payload is rejected (413)', async () => {
  const db = createTestDb();

  // Building a >20MB multipart body by hand would be slow; cap the fixture to a
  // size the handler rejects by temporarily lowering the cap via a large file.
  const big = new Uint8Array(21 * 1024 * 1024); // 21MB of zeros
  const res = await upload(new FakeMedia(), db, withFile(new File([big], 'big.png', { type: 'image/png' })));
  assert.equal(res.status, 413);
  assert.equal((await countImages(db)), 0);
});

// ---------- failure cleanup: D1 insert fails AFTER R2 put ----------

/** Wraps a real db so the images INSERT rejects, simulating a D1 failure. */
function failingInsertDb(db: D1Like): D1Like {
  return {
    prepare(sql: string): D1StatementLike {
      if (/^\s*INSERT INTO images/i.test(sql)) {
        return { bind() { return this; }, first: async () => null, all: async () => ({ results: [] as never[] }), run: async () => { throw new Error('D1_ERROR: simulated insert failure'); } };
      }
      return db.prepare(sql);
    },
  };
}

test('upload endpoint: R2 object is removed when the D1 insert fails', async () => {
  const realDb = createTestDb();
  const media = new FakeMedia();
  const res = await upload(media, failingInsertDb(realDb), withFile(new File([await fixture('image/png')], 'photo.png', { type: 'image/png' })));

  assert.equal(res.status, 500);
  assert.equal((await countImages(realDb)), 0, "no D1 row");
  assert.equal(media.objects.size, 0, 'R2 object deleted after failed insert');
  assert.equal(media.puts.length, 1, 'R2 put happened once');
  assert.equal(media.deletes.length, 1, 'cleanup delete happened once');
  assert.deepEqual(media.deletes, media.puts, 'deleted the same key that was put');
});

// ---------- retrieval regression (the public /images/[id] route path) ----------

test('upload endpoint: stored image can be looked up for the public route and returns 404 for unknown ids', async () => {
  const db = createTestDb();
  const media = new FakeMedia();
  const res = await upload(media, db, withFile(new File([await fixture('image/webp')], 'photo.webp', { type: 'image/webp' })));
  assert.equal(res.status, 200);
  const image = await resImage(res);

  const row = await db.prepare('SELECT r2_original, mime FROM images WHERE id = ?').bind(image.id).first<{ r2_original: string; mime: string }>();
  assert.ok(row, 'D1 lookup works for the public route');
  assert.ok(media.objects.has(row!.r2_original));
  assert.equal(row!.mime, 'image/webp');
  assert.equal(media.objects.get(row!.r2_original)!.byteLength, image.bytes);

  const missing = await db.prepare('SELECT 1 AS x FROM images WHERE id = ?').bind('00000000-0000-4000-8000-000000000000').first();
  assert.equal(missing, null, 'unknown id resolves to nothing (the public route 404s)');
});