// ---------- media fake: in-memory R2 that records puts/deletes ----------

class FakeMedia implements MediaLike {
  objects = new Map<string, Uint8Array>();
  puts: string[] = [];
  deletes: string[] = [];

  async put(key: string, value: ArrayBuffer | Uint8Array) {
    this.puts.push(key);
    this.objects.set(key, value instanceof Uint8Array ? value : new Uint8Array(value));
  }
  async delete(key: string) {
    this.deletes.push(key);
    this.objects.delete(key);
  }
}

// ---------- real image fixtures generated by sharp ----------

async function fixture(mime: 'image/jpeg' | 'image/png' | 'image/webp'): Promise<ArrayBuffer> {
  const b = sharp({ create: { width: 120, height: 80, channels: 3, background: { r: 210, g: 120, b: 60 } } });
  const buf = await (mime === 'image/jpeg' ? b.jpeg() : mime === 'image/png' ? b.png() : b.webp()).toBuffer();
  return buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength) as ArrayBuffer;
}

function formRequest(body: FormData): Request {
  return new Request('http://localhost/api/admin/images/', { method: 'POST', body });
}

const upload = (media: MediaLike, db: D1Like, body: FormData) =>
  handleImageUpload({ db, media, request: formRequest(body) });

const countImages = (db: D1Like) =>
  db.prepare('SELECT COUNT(*) AS n FROM images').first<{ n: number }>().then((r) => r?.n ?? 0);

function withFile(file: Blob, name = 'upload.bin'): FormData {
  const fd = new FormData();
  fd.append('file', file, name);
  return fd;
}

interface UploadBody {
  image: {
    id: string;
    r2Original: string;
    width: number;
    height: number;
    bytes: number;
    mime: string;
    duplicate?: boolean;
  };
}

const resImage = async (res: Response) => {
  const body = (await res.json()) as UploadBody;
  return body.image;
};

// ---------- valid uploads ----------

test('upload endpoint: JPEG -> 200, real dims, D1 row, R2 object', async () => {
  const db = createTestDb();
  const media = new FakeMedia();
  const res = await upload(media, db, withFile(new File([await fixture('image/jpeg')], 'photo.jpg', { type: 'image/jpeg' })));
  assert.equal(res.status, 200);
  const image = await resImage(res);
  assert.equal(image.width, 120);
  assert.equal(image.height, 80);
  assert.equal(image.mime, 'image/jpeg');
  assert.ok(image.bytes > 0);
  assert.match(image.id, /^[0-9a-f-]{36}$/i);

  const row = await db.prepare('SELECT * FROM images WHERE id = ?').bind(image.id).first();
  assert.ok(row);
  assert.equal((row as { width: number }).width, 120);
  assert.equal((row as { height: number }).height, 80);
  assert.ok(media.objects.has(image.r2Original), 'R2 object stored');
  assert.equal(media.deletes.length, 0);
});

