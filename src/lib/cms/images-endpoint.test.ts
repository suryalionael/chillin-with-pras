test('upload endpoint: duplicate hash returns the existing id, no new R2 object', async () => {
  const db = createTestDb();
  const media = new FakeMedia();
  const img = await fixture('image/png');
  const first = await upload(media, db, withFile(new File([img], 'a.png', { type: 'image/png' })));
  assert.equal(first.status, 200);
  const firstImage = await resImage(first);

  const dup = await upload(media, db, withFile(new File([img], 'b.png', { type: 'image/png' })));
  assert.equal(dup.status, 200);
  const dupImage = await resImage(dup);
  assert.equal(dupImage.duplicate, true);
  assert.equal(dupImage.id, firstImage.id);
  assert.equal(media.puts.length, 1, 'no second R2 put for a duplicate');
  const { results } = await db.prepare('SELECT id FROM images WHERE sha256 = (SELECT sha256 FROM images WHERE id = ?)').bind(firstImage.id).all();
  assert.equal(results.length, 1);
});

// ---------- invalid uploads ----------

test('upload endpoint: text file renamed .png is rejected (422), no D1/R2 residue', async () => {
  const db = createTestDb();
  const media = new FakeMedia();
  const res = await upload(media, db, withFile(new File(['this is not an image at all, just plain text bytes'], 'fake.png', { type: 'image/png' })));
  assert.equal(res.status, 422);
  const body = (await res.json()) as { error: { code: string } };
  assert.equal(body.error.code, 'not_an_image');
  assert.equal((await countImages(db)), 0);
  assert.equal(media.objects.size, 0);
  assert.equal(media.puts.length, 0);
});

